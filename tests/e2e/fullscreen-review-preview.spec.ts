import {enterReview} from './enter-review';
import { test, expect } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

test('expanded live previews preserve frames, navigation, session and decisions', async ({ page, request }, info) => {
  const env = JSON.parse(readFileSync(process.env.RTL_MANUAL_ENVIRONMENT!, 'utf8'));
  const report = JSON.parse(readFileSync(join(env.dashboard, 'rtl-report.json'), 'utf8'));
  const finding = report.findings.find((f: any) => f.path.endsWith('/InvoiceTable.tsx') && f.original === '{i.id}');
  const snapshot = () => request.get('http://127.0.0.1:4318/review/workflows?' + new URLSearchParams({ inputDigest: report.inputDigest, policyDigest: report.policyDigest, mode: 'one-by-one' })).then(r => r.json()).then(r => r.workflow);
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('?finding=' + encodeURIComponent(finding.id));
  await enterReview(page);
  await expect(page.locator('.session-identity')).toHaveAttribute('title','One by one review');
  await expect(page.locator('.component-after .embedded-state')).toHaveAttribute('data-preparation-state','ready',{timeout:30000});
  const original = page.locator('iframe[title="Before: original application route"]');
  const candidate = page.locator('iframe[title="After: isolated candidate application route"]');
  const before = page.frameLocator('iframe[title="Before: original application route"]');
  const after = page.frameLocator('iframe[title="After: isolated candidate application route"]');
  await expect(page.locator('.component-after .embedded-state')).toHaveAttribute('data-state', 'ready', { timeout: 25_000 });
  const initial = await snapshot();
  const posts: string[] = [], navigations: string[] = [];
  page.on('request', r => { if (r.url().includes(':4318/') && r.method() === 'POST') posts.push(r.url()); });
  page.on('framenavigated', f => { if (f !== page.mainFrame()) navigations.push(f.url()); });
  const opener = page.getByRole('button', { name: 'Expand original preview', exact: true });
  await opener.scrollIntoViewIfNeeded();
  const location = await opener.boundingBox();
  await original.evaluate(n => { (window as any).__previewOriginal = n; });
  await candidate.evaluate(n => { (window as any).__previewCandidate = n; });
  await opener.click();
  const dialog = page.getByRole('dialog', { name: 'Live application preview' });
  await expect(dialog).toBeVisible();
  await expect(original).toBeVisible(); await expect(candidate).toBeHidden();
  await expect(dialog.getByRole('button', { name: 'Before', exact: true })).toBeFocused();
  const bounds = await dialog.boundingBox();
  expect(bounds).toEqual({ x: 0, y: 0, width: 1600, height: 1000 });
  const size = await original.boundingBox(); expect(size!.width).toBeGreaterThan(1500); expect(size!.height).toBeGreaterThan(850);
  expect(await original.evaluate(n => getComputedStyle(n).transform)).toBe('none');
  expect(await before.locator('body').evaluate(() => innerWidth)).toBe(Math.round(size!.width));
  expect(await page.locator('html').evaluate(n => getComputedStyle(n).overflow)).toBe('hidden');
  await expect(before.locator('.invoice-link bdi')).toHaveCount(0);
  await page.screenshot({ path: info.outputPath('before-only.png') });
  // Real application navigation must survive switching modes, closing, and reopening.
  await before.getByRole('link', { name: 'Customers', exact: true }).click();
  await expect(before.getByRole('heading', { name: 'Customers', exact: true })).toBeVisible();
  await expect(dialog.locator('.preview-current-route')).toContainText('/customers');
  await expect(dialog.locator('.component-before .embedded-state')).toHaveAttribute('data-state', 'navigated');
  const navigationsAfterAppClick = navigations.length;
  await dialog.getByRole('button', { name: 'After', exact: true }).click();
  await expect(original).toBeHidden(); await expect(candidate).toBeVisible();
  await expect(after.locator('.invoice-link > bdi').first()).toHaveText(/INV-/);
  await expect(dialog.locator('.component-after h3')).toContainText(initial.entries.find((e: any) => e.finding.id === finding.id).decision);
  await expect(dialog.locator('.component-after .preview-status')).toContainText(initial.validationPresentation?.status || 'Not run');
  await page.screenshot({ path: info.outputPath('after-only.png') });
  await after.getByRole('textbox', { name: 'Search invoices', exact: true }).fill('INV-');
  await expect(after.getByRole('textbox', { name: 'Search invoices', exact: true })).toHaveValue('INV-');
  await dialog.getByRole('button', { name: 'Split', exact: true }).click();
  await expect(original).toBeVisible(); await expect(candidate).toBeVisible();
  await expect(before.getByRole('heading', { name: 'Customers', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('split.png') });
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(opener).toBeFocused(); await expect(dialog).toHaveCount(0);
  expect((await opener.boundingBox())!.y).toBeCloseTo(location!.y, 0);
  await page.getByRole('button', { name: 'Expand candidate preview', exact: true }).click();
  await expect(candidate).toBeVisible(); await expect(original).toBeHidden();
  await expect(after.getByRole('textbox', { name: 'Search invoices', exact: true })).toHaveValue('INV-');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Expand candidate preview', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Expand', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Split', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await dialog.getByRole('button', { name: 'Before', exact: true }).press('Escape');
  await expect(page.getByRole('button', { name: 'Expand', exact: true })).toBeFocused();
  expect(navigations).toHaveLength(navigationsAfterAppClick);
  expect(await original.evaluate(n => n === (window as any).__previewOriginal)).toBe(true);
  expect(await candidate.evaluate(n => n === (window as any).__previewCandidate)).toBe(true);
  // Deliberate direction changes refresh the owning route using the existing implementation.
  await page.getByRole('button', { name: 'Expand', exact: true }).click();
  await dialog.getByRole('button', { name: 'RTL', exact: true }).click();
  await expect(before.locator('html')).toHaveAttribute('dir', 'rtl'); await expect(after.locator('html')).toHaveAttribute('dir', 'rtl');
  const afterDirection = navigations.length;
  await dialog.getByLabel('Preview viewport', { exact: true }).selectOption('1');
  await expect.poll(() => after.locator('body').evaluate(() => innerWidth)).toBe(768);
  await expect.poll(() => before.locator('body').evaluate(() => innerWidth)).toBe(768);
  await dialog.getByLabel('Preview viewport', { exact: true }).selectOption('2');
  await expect.poll(() => after.locator('body').evaluate(() => innerWidth)).toBe(390);
  await dialog.getByRole('button', { name: 'After', exact: true }).click();
  await expect(after.locator('body')).toBeVisible();
  expect((await candidate.boundingBox())!.height).toBe(850);
  await dialog.getByLabel('Preview viewport', { exact: true }).selectOption('0');
  expect(await after.locator('body').evaluate(() => innerWidth)).toBeGreaterThan(1500);
  expect(navigations).toHaveLength(afterDirection);
  await dialog.getByRole('button', { name: 'LTR', exact: true }).click();
  await expect(after.locator('html')).toHaveAttribute('dir', 'ltr');
  await after.getByRole('textbox', { name: 'Search invoices', exact: true }).fill('INV-');
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeVisible();
  // Dashboard focus trap, including backwards wrap; iframe focus never hides Close.
  await dialog.getByRole('button', { name: 'Before', exact: true }).focus();
  await page.keyboard.press('Shift+Tab'); await expect(candidate).toBeFocused();
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  const beforeRepeats = navigations.length;
  for (let i = 0; i < 3; i++) {
    await opener.click(); await dialog.getByRole('button', { name: 'After', exact: true }).click();
    await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  }
  expect(navigations).toHaveLength(beforeRepeats);
  expect(posts).toEqual([]); expect(await snapshot()).toEqual(initial);
  expect(page.url()).toContain(encodeURIComponent(finding.id));
  expect(await page.locator('[inert]').count()).toBe(0);
  expect(errors).toEqual([]);
  await page.setViewportSize({ width: 900, height: 700 });
  await page.getByRole('button', { name: 'Expand candidate preview', exact: true }).click();
  await dialog.getByLabel('Preview viewport', { exact: true }).selectOption('1');
  expect(await after.locator('body').evaluate(() => innerWidth)).toBe(768);
  expect(await dialog.locator('.component-after .embedded-viewport').evaluate(n => n.scrollHeight > n.clientHeight)).toBe(true);
  await dialog.getByLabel('Preview viewport', { exact: true }).selectOption('0');
  expect(await after.locator('body').evaluate(() => innerWidth)).toBeGreaterThan(850);
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await page.setViewportSize({ width: 1600, height: 1000 });
  const second = report.findings.find((f: any) => f.path === finding.path && f.id !== finding.id && f.original === '{i.id}');
  await page.locator('button.finding').filter({ hasText: second.path + ':' + second.range.start.line + ':' + second.range.start.column }).click();
  await page.getByRole('button', { name: 'Expand original preview', exact: true }).click();
  await page.goBack();
  await expect(dialog).toHaveCount(0);
  expect(await page.locator('[inert]').count()).toBe(0);
  expect(await page.locator('html').evaluate(n => getComputedStyle(n).overflow)).not.toBe('hidden');
  expect(page.url()).toContain(encodeURIComponent(finding.id));
  expect(posts).toEqual([]); expect(await snapshot()).toEqual(initial); expect(errors).toEqual([]);
  const evidence = JSON.stringify({ workflowId: initial.id, sessionId: initial.session.id, candidateRoot: initial.session.candidateRoot, posts, errors, preservedFrames: true, preservedNavigation: true, dialogBox: bounds, originalBox: size, direction: ['ltr', 'rtl'], viewports: ['auto', 768, 390] }, null, 2);
  writeFileSync(info.outputPath('verification.json'), evidence);
  await info.attach('fullscreen-verification', { body: evidence, contentType: 'application/json' });
});
